#!/usr/bin/env node
'use strict';

/**
 * build-project-profile — 把项目画像烘成手机 App 能用的 Dart。
 *
 * 单一真源：runtime/node/backend/src/services/domain/project/projectProfile/index.js
 * 本脚本只做**确定性落盘**，不新增任何项目知识。
 *
 * 产物：
 *   delivery/mobile/khy-os-client-app/lib/core/config/project_profile.g.dart
 *
 * 为什么 Dart 侧不自己渲染：渲染器只有一份（node），Dart 只持有烘好的文本。
 * 两边各写一份渲染逻辑，格式就会漂——而漂了的症状是手机上的 AI 和 PC 上的 AI
 * 对同一条红线给出不同表述，没有任何一方会报错。
 *
 * 构建元数据（版本 / commit / 构建时间）同样在这里取，来源全是 git 与版本真源，
 * 所以 APK 里显示的状态是这个包真实构建时的状态，不是手写的宣传语。
 *
 * 守卫结论**不在本脚本里跑**：整套守卫要几分钟，塞进 APK 构建会让每次打包都慢到
 * 不可用，而且跑不跑得过取决于改动集，不是构建机能决定的。这里只读
 * works/record/ai/GUARD-SNAPSHOT.json（若存在），并原样带上它的 takenAt，
 * 让界面能说清"这是什么时候的结论"。要现跑用
 * scripts/project-profile/record-guard-snapshot.js。
 *
 * 用法：
 *   node scripts/project-profile/build-project-profile.js
 */

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const REPO = path.resolve(__dirname, '..', '..');
const PROFILE_MODULE = path.join(
  REPO,
  'runtime/node/backend/src/services/domain/project/projectProfile/index.js',
);
const OUT = path.join(
  REPO,
  'delivery/mobile/khy-os-client-app/lib/core/config/project_profile.g.dart',
);
const GUARD_SNAPSHOT = path.join(REPO, 'works/record/ai/GUARD-SNAPSHOT.json');

/** git 取一个值，取不到返回空串——没有 git 的构建环境不该让整个脚本崩。 */
function git(args) {
  try {
    return execFileSync('git', args, { cwd: REPO, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

/** Dart 字符串字面量。JSON 转义与 Dart 在这类纯文本上一致，直接复用。 */
function dartStr(value) {
  return JSON.stringify(String(value));
}

function readGuardSnapshot() {
  try {
    const parsed = JSON.parse(fs.readFileSync(GUARD_SNAPSHOT, 'utf8'));
    if (!parsed || typeof parsed !== 'object') return null;
    return parsed;
  } catch {
    return null;
  }
}

function main() {
  const profile = require(PROFILE_MODULE);

  const versionTracks = profile.readVersionTracks(REPO);
  const baseSection = profile.renderProfileSection({ versionTracks });
  const commit = git(['rev-parse', '--short', 'HEAD']);
  const commitDate = git(['log', '-1', '--format=%cI']);
  const buildTime = new Date().toISOString();
  const snapshot = readGuardSnapshot();

  const lines = [];
  lines.push('// GENERATED by scripts/project-profile/build-project-profile.js — DO NOT EDIT.');
  lines.push('//');
  lines.push('// Single source of truth:');
  lines.push('//   runtime/node/backend/src/services/domain/project/projectProfile/index.js');
  lines.push('//');
  lines.push('// Why this file is generated rather than hand-written: the renderer lives in');
  lines.push('// node and only here. Two renderers would drift, and drifted copies mean the');
  lines.push('// phone AI and the PC AI describe the same red line differently — with nothing');
  lines.push('// to report the mismatch.');
  lines.push('');
  lines.push('/// 项目画像与构建元数据（生成物）。');
  lines.push('///');
  lines.push('/// 由 scripts/project-profile/build-project-profile.js 落盘，勿手改。');
  lines.push('library;');
  lines.push('');
  lines.push('/// 项目画像的结构化部分。界面与测试可直接读，不必去解析烘好的文本。');
  lines.push('class ProjectProfileData {');
  lines.push(`  static const String name = ${dartStr(profile.PROJECT_PROFILE.name)};`);
  lines.push(`  static const String kind = ${dartStr(profile.PROJECT_PROFILE.kind)};`);
  lines.push(`  static const String distribution = ${dartStr(profile.PROJECT_PROFILE.distribution)};`);
  lines.push(`  static const String oneLiner = ${dartStr(profile.PROJECT_PROFILE.oneLiner)};`);
  lines.push('  static const String languageRule = ' +
    `${dartStr(profile.PROJECT_PROFILE.languageRule)};`);
  lines.push('');
  lines.push('  /// 红线（R1–R4）。任一破线 = 立即停手，须用户明确点头方可继续。');
  lines.push('  static const List<List<String>> redLines = [');
  for (const [id, rule] of profile.PROJECT_PROFILE.redLines) {
    lines.push(`    [${dartStr(id)}, ${dartStr(rule)}],`);
  }
  lines.push('  ];');
  lines.push('');
  lines.push('  /// 行为准则。只收与「AI 动手」直接相关的几条。');
  lines.push('  static const List<List<String>> behaviorRules = [');
  for (const [id, rule] of profile.PROJECT_PROFILE.behaviorRules) {
    lines.push(`    [${dartStr(id)}, ${dartStr(rule)}],`);
  }
  lines.push('  ];');
  lines.push('');
  lines.push('  /// 结构速查。');
  lines.push('  static const List<List<String>> layout = [');
  for (const [dir, what] of profile.PROJECT_PROFILE.layout) {
    lines.push(`    [${dartStr(dir)}, ${dartStr(what)}],`);
  }
  lines.push('  ];');
  lines.push('}');
  lines.push('');
  lines.push('/// 这个 APK 是凭什么构建出来的。');
  lines.push('///');
  lines.push('/// 全部来自 git 与版本真源，不是手写的宣传语——用户问"这个包是什么状态"，');
  lines.push('/// 答案必须是可核对的。');
  lines.push('class BuildInfo {');
  lines.push('  final String commit;');
  lines.push('  final String commitDate;');
  lines.push('  final String buildTime;');
  lines.push('  final List<VersionTrack> versionTracks;');
  lines.push('');
  lines.push('  /// 守卫结论快照；null = 构建时没有记录。');
  lines.push('  ///');
  lines.push('  /// 带 takenAt 是因为结论会过期：显示一个没有日期的绿灯比不显示更糟。');
  lines.push('  final GuardSnapshot? guards;');
  lines.push('');
  lines.push('  const BuildInfo({');
  lines.push('    required this.commit,');
  lines.push('    required this.commitDate,');
  lines.push('    required this.buildTime,');
  lines.push('    required this.versionTracks,');
  lines.push('    this.guards,');
  lines.push('  });');
  lines.push('');
  lines.push('  static final BuildInfo current = BuildInfo(');
  lines.push(`    commit: ${dartStr(commit)},`);
  lines.push(`    commitDate: ${dartStr(commitDate)},`);
  lines.push(`    buildTime: ${dartStr(buildTime)},`);
  lines.push('    versionTracks: [');
  for (const t of versionTracks) {
    lines.push(`      VersionTrack(${dartStr(t.track)}, ${dartStr(t.version)}),`);
  }
  lines.push('    ],');
  if (snapshot) {
    lines.push('    guards: GuardSnapshot(');
    lines.push(`      takenAt: ${dartStr(snapshot.takenAt || '')},`);
    lines.push('      results: [');
    for (const r of snapshot.results || []) {
      lines.push(`        GuardResult(${dartStr(r.id || '')}, ${dartStr(r.status || '')},`);
      lines.push(`            ${dartStr(r.detail || '')}),`);
    }
    lines.push('      ],');
    lines.push('    ),');
  }
  // BuildInfo( 的收尾必须在两个分支之外：只在 else 里写会让有快照时括号不配，
  // 而 Dart 编译器只报一个指不到原因的 "Can't find ')'"。
  lines.push('  );');
  lines.push('}');
  lines.push('');
  lines.push('class VersionTrack {');
  lines.push('  final String track;');
  lines.push('  final String version;');
  lines.push('  const VersionTrack(this.track, this.version);');
  lines.push('}');
  lines.push('');
  lines.push('class GuardResult {');
  lines.push('  final String id;');
  lines.push("  /// 'pass' | 'fail' | 'skip'");
  lines.push('  final String status;');
  lines.push('  final String detail;');
  lines.push('  const GuardResult(this.id, this.status, this.detail);');
  lines.push('}');
  lines.push('');
  lines.push('class GuardSnapshot {');
  lines.push('  final String takenAt;');
  lines.push('  final List<GuardResult> results;');
  lines.push('  const GuardSnapshot({required this.takenAt, required this.results});');
  lines.push('}');
  lines.push('');
  lines.push('/// 烘好的画像文本——node 侧渲染器的唯一产物，Dart 不再渲染第二份。');
  lines.push('class ProjectProfileText {');
  lines.push(`  static const String base = ${dartStr(baseSection)};`);
  lines.push('');
  lines.push('  /// 有工作目录时追加的一段。');
  lines.push('  ///');
  lines.push('  /// 直接用渲染器导出的 WORKSPACE_SUFFIX_TEMPLATE，不在这里手抄——');
  lines.push('  /// 手抄一份就必然漂，而漂了没有任何一方会报错。');
  lines.push('  static const String workspaceSuffixTemplate =');
  lines.push(`      ${dartStr(profile.WORKSPACE_SUFFIX_TEMPLATE)};`);
  lines.push('');
  lines.push('  /// 给系统提示用：挑了工作目录就把那几行带上，没挑就不带。');
  lines.push('  ///');
  lines.push('  /// 不渲染"当前工作目录：undefined"——模型会以为有个叫 undefined 的目录。');
  lines.push('  static String section({String? workspaceRoot}) {');
  lines.push('    final root = (workspaceRoot ?? \'\').trim();');
  lines.push("    if (root.isEmpty) return base;");
  lines.push("    return base + workspaceSuffixTemplate.replaceFirst('%s', root);");
  lines.push('  }');
  lines.push('}');
  lines.push('');

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join('\n'));

  console.log(`wrote ${path.relative(REPO, OUT)}`);
  console.log(`  commit      ${commit || '(no git)'}`);
  console.log(`  build time  ${buildTime}`);
  console.log(`  tracks      ${versionTracks.map((t) => `${t.track}=${t.version}`).join(', ') || '(none)'}`);
  console.log(`  guards      ${snapshot ? `snapshot taken ${snapshot.takenAt || '(no date)'}` : 'none recorded'}`);
}

main();
