/**
 * petAssetShape —— 桌宠 3D 资产的**形状**判定。
 *
 * 为什么需要它：第三形态「写实真人」的模型槽位（`khy-pet-*-realistic.glb`）现在装的是
 * **浮雕派生的 2.5D 网格**（真人立绘 + 厚度 + 起伏），而槽位名里**不带**「浮雕」——
 * 名字只表示「这是第三形态的模型位」，不表示实现方式。外部 AI 3D 服务给出
 * 真扫描网格后，同名文件覆盖即可，渲染端不用改代码。
 *
 * 于是「能不能整圈转」不能按**形态名**判，必须按**网格的实际形状**判：
 *   · 板状（一块有厚度的平板）：整圈转台只会露出一条侧边，背面还是镜像 →
 *     只能小角度摆，形体永远读得出是那张脸；
 *   · 立体（全身拓扑）：可以整圈自转。
 *
 * 按形状判的实际好处：槽位换成真扫描网格后，自转策略会**自己**从「轻摆」
 * 切回「整圈转」，不需要有人记得去改渲染端的形态分支。
 */

import type { GlbBounds } from './glbLoader'

/**
 * 板状判定阈值：网格深度（z 向跨度）不足高度的这个比例，就是「一块平板」。
 *
 * 实测深度/高度比（本仓真实资产）：
 *   立绘浮雕 0.10 / 0.10，真人浮雕 0.06 / 0.06，Q 版立体模型 0.57 / 0.49。
 * 阈值取 0.15：薄板侧留 1.4× 余量，立体侧离得远（3 倍以上）。
 */
export const PLATE_DEPTH_RATIO = 0.15

/**
 * 这块网格是不是「一块有厚度的平板」。
 *
 * 判据只看**深度相对高度的比例**，不看形态名：网格的形状是事实，
 * 形态名只是人给的标签 —— 标签会过期，事实不会。
 */
export function isPlateLike(bounds: GlbBounds): boolean {
  const height = bounds.max[1] - bounds.min[1]
  if (!(height > 0)) return false
  const depth = bounds.max[2] - bounds.min[2]
  return depth / height < PLATE_DEPTH_RATIO
}
